-- Контекст заявки с публичного сайта — структурно, а не только текстом.
--
-- Страницы раздела «Услуги» (/uslugi/sdat-kvartiru и соседние) передают
-- вместе с лидом выбранный тариф, район, комнатность, ставку аренды и
-- посчитанные калькулятором суммы. Человекочитаемая версия уходит в `comment`
-- (агент видит без раскопок в JSON), структурная — сюда, чтобы потом считать
-- конверсию по тарифам и страницам.
--
-- Колонка nullable и без дефолта: у лидов из CRM, Telegram и импорта
-- метаданных нет, и это нормально.
alter table public.leads add column if not exists metadata jsonb;

comment on column public.leads.metadata is
  'Структурный контекст заявки с сайта: page, tariffId, district, rooms, rate, calc. Пишет только /api/public/leads.';
