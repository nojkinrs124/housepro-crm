-- Подписка на календарь: персональный токен фида
-- ═══════════════════════════════════════════════════════════════════════════
-- Показы жили только внутри CRM, а агент живёт в календаре телефона. Токен
-- даёт ссылку вида /api/ical/<token>, которую можно подписать в Google-,
-- Яндекс- или Apple-календаре: события подтягиваются сами, без ручного
-- переноса и без OAuth-интеграции с каждым поставщиком календаря.
--
-- Токен — секрет: тот, кто знает ссылку, видит расписание сотрудника. Поэтому
-- он отзываемый (перегенерация в профиле) и по умолчанию не выдан.

alter table public.users add column if not exists "ical_token" text;

create unique index if not exists idx_users_ical_token
  on public.users(ical_token) where ical_token is not null;
