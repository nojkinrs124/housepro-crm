-- Отпечаток файла, из которого статью посеяли.
--
-- Без него `npm run seed:handbook` молча затирал правки, сделанные в самой
-- CRM: сеятель просто перезаписывал body содержимым файла. Правка терялась
-- без следа и без предупреждения — узнать об этом можно было только заметив,
-- что текст «откатился».
--
-- Отпечаток отвечает на вопрос «менял ли кто-то статью в интерфейсе после
-- последнего посева»: если хеш текущего body не совпадает с сохранённым,
-- значит менял, и перезаписывать нельзя.
alter table public.knowledge_articles
  add column if not exists "source_hash" text;

comment on column public.knowledge_articles.source_hash is
  'sha256 файла docs/handbook/*.md на момент последнего посева. Расхождение с хешем body = статью правили в CRM.';
