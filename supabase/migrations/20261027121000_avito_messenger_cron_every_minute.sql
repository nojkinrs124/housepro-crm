-- Ускорение крона avito-messenger для автоматического диалога: с 15 минут до 1 минуты.
--
-- Зачем: до этой миграции крон только логировал переписку — задержка ответа клиенту
-- не имела значения, человек отвечал сам в приложении Авито когда ему удобно. Теперь
-- крон сам ведёт диалог и назначает показы — задержка до 15 минут на каждое сообщение
-- неприемлема (владелец: "нужно чтобы было без задержек"). pg_cron поддерживает
-- интервалы до 1 минуты; чаще технически возможно через несколько job'ов со сдвигом,
-- но 1 минута достаточна для диалога и не перегружает лимиты Avito API.
--
-- channel-heartbeat не трогаем — у него своя частота обоснована отдельно (черновики
-- канала, не диалог с клиентом в реальном времени).

select cron.unschedule(jobid) from cron.job where jobname = 'avito-messenger';

select cron.schedule(
  'avito-messenger',
  '* * * * *',
  $$select public.call_vercel_cron('/api/cron/avito-messenger', 50000)$$
);
