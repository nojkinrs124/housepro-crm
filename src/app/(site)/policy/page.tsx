import type { Metadata } from 'next'
import { getSiteContacts } from '@/features/site/lib/contacts'
import { CONSENT_VERSION } from '@/lib/consent'

export const metadata: Metadata = {
  title: 'Политика обработки персональных данных — ХаусПро',
  description:
    'Как агентство недвижимости ХаусПро обрабатывает персональные данные: цели, состав данных, сроки хранения и порядок отзыва согласия.',
}

// Публичная страница политики (152-ФЗ). Реквизиты оператора подставляются из
// company_settings, чтобы документ не расходился с реальным юрлицом агентства.
//
// Версия документа (CONSENT_VERSION) хранится рядом с каждой записью о согласии:
// при правке текста ниже обязательно поднимать её в src/lib/consent.ts, иначе
// отметки «согласился с редакцией такой-то» станут недостоверными.

interface Section {
  title: string
  paragraphs: string[]
  items?: string[]
}

export default async function PolicyPage() {
  const contacts = await getSiteContacts()
  const operator = contacts.legalName ?? 'Агентство недвижимости «ХаусПро»'

  const sections: Section[] = [
    {
      title: '1. Общие положения',
      paragraphs: [
        `Настоящая Политика определяет порядок обработки персональных данных оператором — ${operator}` +
          `${contacts.inn ? `, ИНН ${contacts.inn}` : ''}${contacts.ogrn ? `, ОГРН ${contacts.ogrn}` : ''}` +
          // Адрес из настроек часто уже заканчивается точкой — вторую не ставим.
          `${contacts.address ? `, адрес: ${contacts.address.replace(/\.$/, '')}` : ''}.`,
        'Политика составлена в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных» и применяется ко всем данным, которые оператор получает от субъектов персональных данных.',
      ],
    },
    {
      title: '2. Какие данные обрабатываются',
      paragraphs: ['Оператор обрабатывает данные, которые субъект сообщает сам:'],
      items: [
        'фамилия, имя, отчество;',
        'номер телефона, адрес электронной почты, аккаунты в мессенджерах;',
        'сведения об интересующем объекте недвижимости и параметрах поиска;',
        'при заключении договора — паспортные данные, адрес регистрации, банковские реквизиты;',
        'для представителей юридических лиц — наименование организации, ИНН, КПП, ОГРН, должность и основание полномочий.',
      ],
    },
    {
      title: '3. Цели обработки',
      paragraphs: ['Данные обрабатываются исключительно для:'],
      items: [
        'ответа на обращение и подбора объектов недвижимости;',
        'организации показов и переговоров;',
        'подготовки, заключения и исполнения договоров;',
        'расчётов по договорам и бухгалтерского учёта;',
        'исполнения требований законодательства РФ.',
      ],
    },
    {
      title: '4. Правовые основания',
      paragraphs: [
        'Обработка ведётся на основании согласия субъекта персональных данных, а также договоров, стороной которых является субъект, и требований законодательства РФ.',
      ],
    },
    {
      title: '5. Сроки хранения',
      paragraphs: [
        'Данные хранятся не дольше, чем этого требуют цели обработки. Данные обращений, не приведших к договору, хранятся не более трёх лет с момента последнего контакта. Данные по заключённым договорам хранятся в течение срока, установленного законодательством для соответствующих документов.',
      ],
    },
    {
      title: '6. Передача третьим лицам',
      paragraphs: [
        'Оператор не продаёт и не передаёт персональные данные третьим лицам, за исключением случаев, прямо предусмотренных законом, а также привлечённых для исполнения договора лиц (например, банков и нотариусов) — в объёме, необходимом для совершения сделки.',
      ],
    },
    {
      title: '7. Защита данных',
      paragraphs: [
        'Оператор принимает правовые, организационные и технические меры для защиты персональных данных от неправомерного доступа, уничтожения, изменения и распространения: доступ к данным разграничен по ролям сотрудников, соединения защищены шифрованием, действия с данными журналируются.',
      ],
    },
    {
      title: '8. Права субъекта и отзыв согласия',
      paragraphs: [
        'Субъект вправе получить сведения об обработке своих данных, потребовать их уточнения, блокирования или уничтожения, а также в любой момент отозвать согласие на обработку.',
        `Для этого достаточно направить обращение на ${contacts.email}${contacts.phone ? ` или сообщить по телефону ${contacts.phone}` : ''}. Согласие считается отозванным с момента получения обращения; после отзыва данные используются только в объёме, который оператор обязан хранить по закону.`,
      ],
    },
    {
      title: '9. Изменения политики',
      paragraphs: [
        `Действующая редакция Политики публикуется на этой странице. Версия документа: ${CONSENT_VERSION}.`,
      ],
    },
  ]

  return (
    <div className="max-w-3xl mx-auto px-4 py-12 space-y-8">
      <header className="space-y-2">
        <h1 className="text-[27px] font-bold text-[var(--hp-ink)] tracking-tight leading-tight">
          Политика обработки персональных данных
        </h1>
        <p className="text-[var(--hp-sub)] text-sm font-medium">
          Редакция от {new Date(CONSENT_VERSION).toLocaleDateString('ru-RU')} · оператор — {operator}
        </p>
      </header>

      {sections.map((section) => (
        <section key={section.title} className="space-y-3">
          <h2 className="font-bold text-[var(--hp-ink)] text-[17px]">{section.title}</h2>
          {section.paragraphs.map((text) => (
            <p key={text} className="text-sm leading-relaxed text-[var(--hp-sub)]">
              {text}
            </p>
          ))}
          {section.items && (
            <ul className="list-disc pl-5 space-y-1.5">
              {section.items.map((item) => (
                <li key={item} className="text-sm leading-relaxed text-[var(--hp-sub)]">
                  {item}
                </li>
              ))}
            </ul>
          )}
        </section>
      ))}
    </div>
  )
}
