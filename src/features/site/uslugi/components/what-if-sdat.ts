/** Русское множественное число: pluralRu(5, ['день', 'дня', 'дней']) → «дней» */
function pluralRu(n: number, forms: [string, string, string]): string {
  const abs = Math.abs(n) % 100
  const last = abs % 10
  if (abs > 10 && abs < 20) return forms[2]
  if (last > 1 && last < 5) return forms[1]
  if (last === 1) return forms[0]
  return forms[2]
}

const days = (n: number) => `${n} ${pluralRu(n, ['день', 'дня', 'дней'])}`

const RATES_WORDS: Record<number, string> = { 1: 'одной', 2: 'двух', 3: 'трёх' }

/** «до одной месячной ставки» / «до двух месячных ставок» / «до 4 месячных ставок» */
function monthlyRatesPhrase(n: number): string {
  const word = RATES_WORDS[n] ?? String(n)
  return n === 1 ? `${word} месячной ставки` : `${word} месячных ставок`
}

const DAYS_IN_MONTH = 30

const MONTHS_WORDS: Record<number, string> = {
  1: 'Один месяц',
  2: 'Два месяца',
  3: 'Три месяца',
  4: 'Четыре месяца',
  5: 'Пять месяцев',
  6: 'Шесть месяцев',
}

/**
 * Срок уведомления о расторжении с большой буквы — начало предложения:
 * 60 → «Два месяца», 90 → «Три месяца», 45 → «45 дней».
 */
function noticeDaysLabel(n: number): string {
  if (n > 0 && n % DAYS_IN_MONTH === 0) {
    const word = MONTHS_WORDS[n / DAYS_IN_MONTH]
    if (word) return word
  }
  return days(n)
}

