/**
 * Пользовательское сообщение: факты из CRM (только заполненные) + сырые вводные агента.
 * Вводные не обрезаются — лимит длины проверяет Zod на входе в route.
 */
export function buildUserPrompt(property: ListingPropertyInput, rawInput: string): string {
  const facts = propertyListingFacts(property)
  const crmBlock = facts.length
    ? facts.map(f => `${f.label}: ${f.value}`).join('\n')
    : '(данных в CRM нет)'
  const raw = rawInput.trim() || '(вводных нет — используй только данные из CRM)'

  return [
    'ДАННЫЕ ИЗ CRM:',
    crmBlock,
    '',
    'СЫРЫЕ ВВОДНЫЕ ОТ АГЕНТА:',
    raw,
    '',
    'Сгенерируй объявление по правилам.',
  ].join('\n')
}
