// Страницы согласий, которые подшиваются к договору перед отправкой на подпись.
//
// Два разных документа, их часто путают:
//
// 1. Соглашение об использовании простой электронной подписи (63-ФЗ, ст. 6 ч. 2
//    и ст. 9). Без него ПЭП юридической силы не имеет: закон признаёт документ,
//    подписанный простой подписью, равнозначным бумажному только если стороны
//    заранее договорились об этом. Договорённость и оформляется этим листом.
//
// 2. Согласие на обработку персональных данных (152-ФЗ, ст. 9). Оно нужно само
//    по себе — независимо от того, как подписывается договор.
//
// Тексты лежат в коде, а не в шаблонах DOCX, сознательно: шаблоны загружает
// агентство, и забытое согласие в шаблоне обнаружилось бы только в суде.

import type { PdfBlock } from './text-pdf'

/**
 * Версия текста согласий. Пишется рядом с записью о подписании: через год нужно
 * будет доказать, с какой именно редакцией согласился конкретный человек.
 * При правке текстов ниже — обязательно поднимать.
 */
export const SIGNING_CONSENT_VERSION = '2026-09-02'

export interface ConsentContext {
  /** Оператор ПД и сторона соглашения о ПЭП — исполнитель по договору. */
  operatorName: string
  operatorInn: string
  operatorAddress: string
  operatorPhone: string
  operatorEmail: string | null
  /** Подписант — физическое лицо, которому уходит СМС. */
  signerName: string
  signerPhone: string
  /** «Договор № 12 от 02.09.2026» — чтобы согласие нельзя было отнести к другому документу. */
  documentLabel: string
  /** Дата подписания в формате дд.мм.гггг. */
  date: string
}

const SERVICE_NAME = 'сервис электронной подписи «Подпислон» (podpislon.ru)'

