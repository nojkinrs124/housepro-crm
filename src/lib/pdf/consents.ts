/**
 * Оба согласия одним набором блоков — печатаются в конце файла договора,
 * чтобы клиент подписывал их тем же кодом, что и сам договор.
 */
export function consentPagesBlocks(ctx: ConsentContext): PdfBlock[] {
  return [...pepBlocks(ctx), ...personalDataBlocks(ctx)]
}
