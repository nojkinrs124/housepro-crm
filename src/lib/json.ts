import type { Json } from '@/types/database'

/**
 * Значение для jsonb-колонки.
 *
 * После перехода на сгенерированные типы схемы jsonb-колонки имеют точный тип
 * `Json` (рекурсивное объединение примитивов, массивов и объектов). Структуры
 * приложения — интерфейсы и `Record<string, unknown>` — в него не выводятся
 * автоматически: TypeScript не может доказать, что в поле `unknown` лежит
 * что-то сериализуемое, хотя по факту это всегда результат разбора формы или
 * ответа API.
 *
 * Приведение здесь одно и в одном месте, вместо `as unknown as Json` в каждом
 * Server Action. Использовать только для данных, которые действительно уходят
 * в jsonb: результат JSON.parse, разобранная форма, снапшот ответа внешнего API.
 */
export function toJson<T>(value: T): Json {
  return value as unknown as Json
}
